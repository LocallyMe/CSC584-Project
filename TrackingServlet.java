    /**
     * Handles the HTTP <code>POST</code> method.
     *
     * @param request servlet request
     * @param response servlet response
     * @throws ServletException if a servlet-specific error occurs
     * @throws IOException if an I/O error occurs
     */
    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        //processRequest(request, response);
    String trackingNumber = request.getParameter("trackingNumber");
        
        if (trackingNumber != null && !trackingNumber.trim().isEmpty()) {
            TrackingData trackingData = trackingDAO.getTrackingDetails(trackingNumber.trim());
            
            if (trackingData != null) {
                request.setAttribute("trackingData", trackingData);
            } else {
                request.setAttribute("error", "Tracking number not found. Please try again.");
            }
        }
        
        // Forward to the View (JSP)
        request.getRequestDispatcher("trackOrder.jsp").forward(request, response);
    }

